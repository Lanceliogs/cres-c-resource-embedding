/*
 * cres_tool.c — C Resource Embedding code generator
 *
 * Reads a manifest file and produces a .h/.c pair with embedded byte arrays.
 * Supports optional zlib compression via miniz.
 *
 * Usage:
 *   cres -m <manifest> -o <output_base> [--guard GUARD] [--prefix PREFIX]
 *
 * Manifest format:
 *   # comment
 *   path/to/file.bin
 *   z path/to/compress.txt
 *   @path/to/directory/
 *   z @path/to/compressed_dir/
 *   "path with spaces/file.txt"
 *   z @"dir with spaces/"
 *
 * Build:
 *   gcc -std=c11 -o cres cres_tool.c miniz.c -DCRES_COMPRESSION
 */

#define _XOPEN_SOURCE 700
#include <stdarg.h>
#include <ctype.h>
#include <dirent.h>
#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

#ifdef CRES_COMPRESSION
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wunused-function"
#include "miniz.h"
#pragma GCC diagnostic pop
#endif

#define MAX_RESOURCES 4096
#define BYTES_PER_LINE 16

typedef struct {
    char filepath[1024];
    char symbol[256];
    char key[1024];
    int  compress_level; /* 0 = raw, 1-9 = compression level */
    size_t orig_size;    /* filled during code generation */
} Resource;

static Resource resources[MAX_RESOURCES];
static int resource_count = 0;

static char manifest_dir[1024] = ".";

/* --- Utility ------------------------------------------------------------ */

static void die(const char *fmt, ...)
{
    va_list ap;
    fprintf(stderr, "cres: error: ");
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fprintf(stderr, "\n");
    exit(1);
}

static void symbolize(const char *input, char *out, size_t out_size)
{
    size_t j = 0;
    for (size_t i = 0; input[i] && j < out_size - 1; i++) {
        char c = input[i];
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
            (c >= '0' && c <= '9'))
            out[j++] = c;
        else
            out[j++] = '_';
    }
    out[j] = '\0';

    /* strip leading underscores */
    char *s = out;
    while (*s == '_') s++;
    if (s != out) memmove(out, s, strlen(s) + 1);

    /* strip trailing underscores */
    size_t len = strlen(out);
    while (len > 0 && out[len - 1] == '_') out[--len] = '\0';
}

static int is_dir(const char *path)
{
    struct stat st;
    return stat(path, &st) == 0 && S_ISDIR(st.st_mode);
}

static int is_file(const char *path)
{
    struct stat st;
    return stat(path, &st) == 0 && S_ISREG(st.st_mode);
}

static void path_join(char *out, size_t out_size,
                      const char *a, const char *b)
{
    size_t alen = strlen(a);
    if (alen > 0 && a[alen - 1] == '/')
        snprintf(out, out_size, "%s%s", a, b);
    else
        snprintf(out, out_size, "%s/%s", a, b);
}

static void add_resource(const char *filepath, const char *symbol,
                         const char *key, int compress_level)
{
    if (resource_count >= MAX_RESOURCES)
        die("too many resources (max %d)", MAX_RESOURCES);

    Resource *r = &resources[resource_count++];
    snprintf(r->filepath, sizeof(r->filepath), "%s", filepath);
    snprintf(r->symbol, sizeof(r->symbol), "%s", symbol);
    snprintf(r->key, sizeof(r->key), "%s", key);
    r->compress_level = compress_level;
}

/* --- Collision detection ------------------------------------------------ */

static void check_symbol_collisions(const char *prefix)
{
    for (int i = 0; i < resource_count; i++) {
        for (int j = i + 1; j < resource_count; j++) {
            if (strcmp(resources[i].symbol, resources[j].symbol) == 0) {
                die("symbol collision: '%s%s' generated by both:\n"
                    "  - \"%s\"\n"
                    "  - \"%s\"\n"
                    "Rename one of the files to resolve.",
                    prefix, resources[i].symbol,
                    resources[i].key, resources[j].key);
            }
        }
    }
}

/* --- Recursive directory scan ------------------------------------------- */

static void scan_dir(const char *dirpath, const char *rel_prefix,
                     int compress_level)
{
    DIR *d = opendir(dirpath);
    if (!d) die("cannot open directory '%s': %s", dirpath, strerror(errno));

    struct dirent *ent;
    while ((ent = readdir(d)) != NULL) {
        if (ent->d_name[0] == '.') continue;

        char fullpath[1024];
        path_join(fullpath, sizeof(fullpath), dirpath, ent->d_name);

        char relpath[1024];
        if (rel_prefix[0])
            snprintf(relpath, sizeof(relpath), "%s/%s", rel_prefix, ent->d_name);
        else
            snprintf(relpath, sizeof(relpath), "%s", ent->d_name);

        if (is_dir(fullpath)) {
            scan_dir(fullpath, relpath, compress_level);
        } else if (is_file(fullpath)) {
            char sym[256];
            symbolize(relpath, sym, sizeof(sym));
            add_resource(fullpath, sym, relpath, compress_level);
        }
    }

    closedir(d);
}

/* --- Manifest parsing --------------------------------------------------- */

static char *parse_path(char *p, char *out, size_t out_size)
{
    if (*p == '"') {
        p++;
        char *end = strchr(p, '"');
        if (!end) return NULL;
        size_t len = (size_t)(end - p);
        if (len >= out_size) return NULL;
        memcpy(out, p, len);
        out[len] = '\0';
        return end + 1;
    }

    char *start = p;
    while (*p && *p != ' ' && *p != '\t') p++;
    size_t len = (size_t)(p - start);
    if (len >= out_size) return NULL;
    memcpy(out, start, len);
    out[len] = '\0';
    return p;
}

static void resolve_path(const char *raw, char *out, size_t out_size)
{
    if (raw[0] == '/' || (raw[0] != '\0' && raw[1] == ':'))
        snprintf(out, out_size, "%s", raw);
    else
        path_join(out, out_size, manifest_dir, raw);
}

static void parse_manifest(const char *manifest_path)
{
    FILE *f = fopen(manifest_path, "r");
    if (!f) die("cannot open manifest '%s': %s", manifest_path, strerror(errno));

    snprintf(manifest_dir, sizeof(manifest_dir), "%s", manifest_path);
    char *last_slash = strrchr(manifest_dir, '/');
    if (!last_slash) last_slash = strrchr(manifest_dir, '\\');
    if (last_slash)
        *last_slash = '\0';
    else
        snprintf(manifest_dir, sizeof(manifest_dir), ".");

    char line[2048];
    int lineno = 0;
    while (fgets(line, sizeof(line), f)) {
        lineno++;

        size_t len = strlen(line);
        while (len > 0 && (line[len - 1] == '\n' || line[len - 1] == '\r'))
            line[--len] = '\0';

        char *p = line;
        while (*p == ' ' || *p == '\t') p++;
        if (*p == '\0' || *p == '#') continue;

        /* check for compression prefix: z, z1-z9 */
        int compress_level = 0;
        if (*p == 'z') {
            if (p[1] >= '1' && p[1] <= '9' && (p[2] == ' ' || p[2] == '\t')) {
                compress_level = p[1] - '0';
                p += 2;
            } else if (p[1] == ' ' || p[1] == '\t') {
                compress_level = 6; /* MZ_DEFAULT_LEVEL */
                p++;
            }
            if (compress_level)
                while (*p == ' ' || *p == '\t') p++;
        }

        if (*p == '@') {
            /* directory directive: @dir/ or @"dir with spaces/" */
            p++;
            char rawdir[1024];
            char *rest = parse_path(p, rawdir, sizeof(rawdir));
            if (!rest)
                die("line %d: invalid path", lineno);

            /* strip trailing slash */
            size_t dlen = strlen(rawdir);
            while (dlen > 0 && rawdir[dlen - 1] == '/') rawdir[--dlen] = '\0';

            char dirpath[1024];
            resolve_path(rawdir, dirpath, sizeof(dirpath));

            if (!is_dir(dirpath))
                die("line %d: not a directory: '%s'", lineno, dirpath);

            scan_dir(dirpath, rawdir, compress_level);
        } else {
            /* single file */
            char rawpath[1024];
            char *rest = parse_path(p, rawpath, sizeof(rawpath));
            if (!rest)
                die("line %d: invalid path", lineno);

            char fullpath[1024];
            resolve_path(rawpath, fullpath, sizeof(fullpath));

            if (!is_file(fullpath))
                die("line %d: not a file: '%s'", lineno, fullpath);

            char sym[256];
            symbolize(rawpath, sym, sizeof(sym));
            add_resource(fullpath, sym, rawpath, compress_level);
        }
    }

    fclose(f);
}

/* --- Code generation ---------------------------------------------------- */

static uint8_t *read_file(const char *path, size_t *out_size)
{
    FILE *f = fopen(path, "rb");
    if (!f) die("cannot read '%s': %s", path, strerror(errno));

    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);

    if (sz < 0) die("cannot determine size of '%s'", path);

    uint8_t *buf = (uint8_t *)malloc((size_t)sz);
    if (!buf) die("out of memory reading '%s'", path);

    if (sz > 0 && fread(buf, 1, (size_t)sz, f) != (size_t)sz)
        die("short read on '%s'", path);

    fclose(f);
    *out_size = (size_t)sz;
    return buf;
}

static void emit_byte_array(FILE *out, const char *varname,
                            const uint8_t *data, size_t size)
{
    fprintf(out, "static const uint8_t %s[] = {", varname);

    for (size_t i = 0; i < size; i++) {
        if (i % BYTES_PER_LINE == 0)
            fprintf(out, "\n    ");
        fprintf(out, "0x%02x", data[i]);
        if (i + 1 < size)
            fprintf(out, ",");
    }

    fprintf(out, "\n};\n\n");
}

static void generate(const char *output_base, const char *guard,
                     const char *prefix)
{
    char hpath[1024], cpath[1024];
    snprintf(hpath, sizeof(hpath), "%s.h", output_base);
    snprintf(cpath, sizeof(cpath), "%s.c", output_base);

    const char *hfile = strrchr(hpath, '/');
    if (!hfile) hfile = strrchr(hpath, '\\');
    hfile = hfile ? hfile + 1 : hpath;

    int any_compressed = 0;
    for (int i = 0; i < resource_count; i++) {
        if (resources[i].compress_level) { any_compressed = 1; break; }
    }

    /* --- .c file -------------------------------------------------------- */
    FILE *fc = fopen(cpath, "w");
    if (!fc) die("cannot write '%s': %s", cpath, strerror(errno));

    fprintf(fc, "/* Generated by cres — do not edit */\n");
    fprintf(fc, "#include \"%s\"\n\n", hfile);

    /* emit byte arrays */
    for (int i = 0; i < resource_count; i++) {
        size_t raw_size;
        uint8_t *raw_data = read_file(resources[i].filepath, &raw_size);
        resources[i].orig_size = raw_size;

        if (resources[i].compress_level) {
#ifdef CRES_COMPRESSION
            mz_ulong bound = mz_compressBound((mz_ulong)raw_size);
            uint8_t *cbuf = (uint8_t *)malloc(bound);
            if (!cbuf) die("out of memory compressing '%s'", resources[i].filepath);
            mz_ulong csize = bound;
            int status = mz_compress2(cbuf, &csize, raw_data, (mz_ulong)raw_size,
                                      resources[i].compress_level);
            if (status != MZ_OK)
                die("compression failed for '%s' (status %d)", resources[i].filepath, status);

            char varname[300];
            snprintf(varname, sizeof(varname), "_cdata_%s", resources[i].symbol);
            emit_byte_array(fc, varname, cbuf, (size_t)csize);

            fprintf(fc, "/* %s: %zu -> %lu bytes (%.1f%%, level %d) */\n\n",
                    resources[i].key, raw_size, (unsigned long)csize,
                    raw_size > 0 ? (double)csize / (double)raw_size * 100.0 : 0.0,
                    resources[i].compress_level);

            free(cbuf);
#else
            die("compression requested for '%s' but CRES_COMPRESSION not enabled.\n"
                "Rebuild cres with: gcc -DCRES_COMPRESSION -o cres cres_tool.c miniz.c",
                resources[i].filepath);
#endif
        } else {
            char varname[300];
            snprintf(varname, sizeof(varname), "_data_%s", resources[i].symbol);
            emit_byte_array(fc, varname, raw_data, raw_size);
        }

        free(raw_data);
    }

    /* emit table */
    fprintf(fc, "CResEntry %stable[] = {\n", prefix);
    for (int i = 0; i < resource_count; i++) {
        if (resources[i].compress_level) {
            fprintf(fc, "    { \"%s\", NULL, %zu, _cdata_%s, sizeof(_cdata_%s) },\n",
                    resources[i].key, resources[i].orig_size,
                    resources[i].symbol, resources[i].symbol);
        } else {
            fprintf(fc, "    { \"%s\", _data_%s, sizeof(_data_%s), NULL, 0 },\n",
                    resources[i].key, resources[i].symbol, resources[i].symbol);
        }
    }
    fprintf(fc, "};\n");
    fprintf(fc, "const size_t %stable_count = sizeof(%stable) / sizeof(%stable[0]);\n\n",
            prefix, prefix, prefix);

    /* emit direct-access pointers into the table */
    for (int i = 0; i < resource_count; i++) {
        fprintf(fc, "CResEntry *const %s%s = &%stable[%d];\n",
                prefix, resources[i].symbol, prefix, i);
    }

    fclose(fc);

    /* --- .h file -------------------------------------------------------- */
    FILE *fh = fopen(hpath, "w");
    if (!fh) die("cannot write '%s': %s", hpath, strerror(errno));

    fprintf(fh, "/* Generated by cres — do not edit */\n");
    fprintf(fh, "#ifndef %s\n", guard);
    fprintf(fh, "#define %s\n\n", guard);
    fprintf(fh, "#include \"cres.h\"\n\n");

    if (any_compressed)
        fprintf(fh, "#ifndef CRES_COMPRESSION\n#define CRES_COMPRESSION\n#endif\n\n");

    fprintf(fh, "extern CResEntry %stable[];\n", prefix);
    fprintf(fh, "extern const size_t %stable_count;\n\n", prefix);

    for (int i = 0; i < resource_count; i++) {
        fprintf(fh, "extern CResEntry *const %s%s;\n",
                prefix, resources[i].symbol);
    }

    fprintf(fh, "\n#endif /* %s */\n", guard);

    fclose(fh);

    fprintf(stderr, "cres: generated %s and %s (%d resources", hpath, cpath, resource_count);
    if (any_compressed) {
        int nc = 0;
        for (int i = 0; i < resource_count; i++)
            if (resources[i].compress_level) nc++;
        fprintf(stderr, ", %d compressed", nc);
    }
    fprintf(stderr, ")\n");
}

/* --- CLI ---------------------------------------------------------------- */

static void usage(void)
{
    fprintf(stderr,
        "Usage: cres -m <manifest> -o <output_base> [options]\n"
        "\n"
        "Options:\n"
        "  -m, --manifest <file>    Manifest file listing resources\n"
        "  -o, --output <base>      Output base name (generates <base>.h and <base>.c)\n"
        "      --guard <name>       Custom include guard (default: auto from output name)\n"
        "      --prefix <prefix>    Symbol prefix (default: cres_)\n"
        "  -h, --help               Show this help\n"
    );
    exit(1);
}

static void auto_guard(const char *output_base, char *guard, size_t guard_size)
{
    const char *base = strrchr(output_base, '/');
    if (!base) base = strrchr(output_base, '\\');
    base = base ? base + 1 : output_base;

    size_t j = 0;
    for (size_t i = 0; base[i] && j < guard_size - 3; i++) {
        char c = base[i];
        if (c >= 'a' && c <= 'z')
            guard[j++] = c - 32;
        else if ((c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9'))
            guard[j++] = c;
        else
            guard[j++] = '_';
    }
    guard[j++] = '_';
    guard[j++] = 'H';
    guard[j] = '\0';
}

int main(int argc, char **argv)
{
    const char *manifest_path = NULL;
    const char *output_base = NULL;
    char guard[256] = {0};
    char prefix[128] = "cres_";

    for (int i = 1; i < argc; i++) {
        if ((strcmp(argv[i], "-m") == 0 || strcmp(argv[i], "--manifest") == 0) && i + 1 < argc) {
            manifest_path = argv[++i];
        } else if ((strcmp(argv[i], "-o") == 0 || strcmp(argv[i], "--output") == 0) && i + 1 < argc) {
            output_base = argv[++i];
        } else if (strcmp(argv[i], "--guard") == 0 && i + 1 < argc) {
            snprintf(guard, sizeof(guard), "%s", argv[++i]);
        } else if (strcmp(argv[i], "--prefix") == 0 && i + 1 < argc) {
            snprintf(prefix, sizeof(prefix), "%s", argv[++i]);
        } else if (strcmp(argv[i], "-h") == 0 || strcmp(argv[i], "--help") == 0) {
            usage();
        } else {
            fprintf(stderr, "cres: unknown option '%s'\n", argv[i]);
            usage();
        }
    }

    if (!manifest_path || !output_base) {
        fprintf(stderr, "cres: -m and -o are required\n");
        usage();
    }

    if (!guard[0])
        auto_guard(output_base, guard, sizeof(guard));

    parse_manifest(manifest_path);

    if (resource_count == 0)
        die("no resources found in manifest '%s'", manifest_path);

    check_symbol_collisions(prefix);

    generate(output_base, guard, prefix);

    return 0;
}
